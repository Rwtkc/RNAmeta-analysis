const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require(process.env.TYPESCRIPT_MODULE || 'typescript');
const source = fs.readFileSync(path.join(__dirname, '../frontend/rnaenrich-core.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const context = { exports: {} }; vm.runInNewContext(compiled.outputText, context);
const core = context.exports;
const a = core.parseBed('A', '1\t0\t10\nchr1\t0\t10\nchr1\t20\t30\nchr1\t5\t5\n');
const b = core.parseBed('B', 'chr1\t0\t10\nchr1\t30\t40\n');
assert.equal(a.records.length, 2); assert.equal(a.duplicateCount, 1); assert.equal(a.invalidLines.length, 1);
const exact = core.compareBeds([a,b], 'exact', null)[0];
assert.equal(exact.overlapCount, 1); assert.equal(exact.jaccard, 1/3); assert.equal(exact.pValue, null);
const boundary = core.compareBeds([core.parseBed('L','1\t0\t10'),core.parseBed('R','1\t10\t20')], 'interval', null)[0];
assert.equal(boundary.overlapCount, 0); assert.equal(boundary.overlapBp, 0);
const overlap = core.compareBeds([core.parseBed('L','1\t0\t10'),core.parseBed('R','1\t5\t15')], 'interval', null)[0];
assert.equal(overlap.overlapBp, 5); assert.equal(overlap.jaccard, 1/3);
const background = core.compareBeds([a,b], 'exact', 100)[0];
assert(background.pValue > 0 && background.pValue < 1); assert(background.fdr >= background.pValue);
console.log('RNAenrich coordinate normalization, deduplication, exact matching, interval boundaries and background tests passed');
