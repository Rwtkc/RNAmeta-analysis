server <- function(input, output, session) {
  rnameta_cache_cleanup_due()

  analysis_lock <- reactiveVal(NULL)

  observe({
    lock_owner <- analysis_lock()
    session$sendCustomMessage(
      "rnameta-analysis-lock",
      list(locked = !is.null(lock_owner))
    )
  })

  mod_welcome_server("welcome")
  upload_run <- mod_upload_run_server("upload_run")
  mod_gene_type_server("gene_type", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_gene_matrix_server("gene_matrix", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_peak_gene_size_server("peak_gene_size", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_peak_exon_size_server("peak_exon_size", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_peak_exon_type_server("peak_exon_type", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_peak_exon_num_server("peak_exon_num", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_peak_distribution_server("peak_distribution", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_browser_server("genome_browser", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_structure_server("structure", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_transcription_server("transcription", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_translation_server("translation", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_splicesite_server("splicesite", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
  mod_motif_server("motif", upload_context = upload_run$upload_context, analysis_lock = analysis_lock)
}
