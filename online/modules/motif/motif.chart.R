motif_build_chart_payload <- function(result) {
  list(
    title = "Motif Workspace",
    status = result$status,
    jobId = result$job_id,
    jobStatus = result$job_status,
    jobMessage = result$job_message,
    startedAt = result$started_at,
    finishedAt = result$finished_at,
    engineLabel = result$engine_label,
    engine = result$engine,
    analysisMode = result$analysis_mode,
    matching = result$matching_summary,
    sampleName = result$sample_name,
    sourceFile = result$source_file,
    species = result$species,
    subsetLabel = result$sites_subset,
    motifWidth = result$motif_width,
    sequenceWindowWidth = result$sequence_window,
    maxMotifs = result$max_motifs,
    peakCount = result$peak_count,
    queryCount = result$query_count,
    controlCount = result$control_count,
    bundleName = result$bundle_name,
    bundleStatus = result$bundle_status,
    bundleMessage = result$bundle_message,
    resultSource = result$bundle_status,
    commandPreview = result$command_preview,
    expectedOutputs = result$expected_outputs,
    jobPackageDir = result$job_package_dir,
    jobPackageFiles = result$job_package_files,
    jobScriptName = result$job_script_name,
    jobManifestName = result$job_manifest_name,
    notes = result$notes,
    motifs = result$motifs
  )
}
